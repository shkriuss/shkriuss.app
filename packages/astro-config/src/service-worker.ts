/**
 * Builds /sw.js: a small service worker that makes each site work offline.
 *
 * - On install it saves every built file (the "precache"). Hashed build
 *   files already saved by the previous version are copied, not downloaded
 *   again: they never change (Grammar's checker alone is about 20 MB).
 * - Hashed build files (/_astro/…) are served from the cache first: they
 *   never change.
 * - Pages are fetched from the network first, so updates show up right away.
 *   If the network fails, or doesn't answer within NETWORK_TIMEOUT_MS (for
 *   example airplane mode with a VPN on, or a very weak signal), or answers
 *   with an error (5xx, or a 4xx a saved page can't have, audit 4 C-5), the
 *   saved copy is shown instead. Pages are saved only on install, with the build
 *   files of the same version: a page from a newer version, saved next to
 *   older build files, would ask for scripts that aren't there offline.
 * - When a new version takes over, the old cache is deleted, except its
 *   build files the new one doesn't have: pages still open from the old
 *   version may yet ask for them (like a worker they start later). Those are
 *   kept in PREVIOUS_CACHE until the next version. Caches an app manages
 *   itself (names not starting with "shkriuss-") are kept.
 * - Files under /on-demand/ are not saved: they're big, and an app downloads
 *   them only when the person asks (e.g. Grammar's Deep check model, about
 *   385 MB). The app saves them in its own cache, and they're served from
 *   there like any other saved file (docs/adr/0012).
 * - Every saved file is served with the site's security policy now. A file
 *   saved under an older one (the headers changed, the file didn't) would
 *   keep it, and a worker started from it runs under the policy its script
 *   came with (audit 4 C-4).
 * - Push messages (notifications while the app is closed, docs/adr/0009)
 *   are shown as notifications. The browser has already decrypted them.
 * - Tapping a notification (e.g. a Calendar reminder) opens the app, or
 *   switches to it if it's already open.
 */

import { ROBOTS_TXT } from './robots-txt.ts';
import { SECURITY_TXT } from './security-txt.ts';

export interface ServiceWorkerOptions {
  /** URL paths to precache, e.g. ["/", "/privacy/", "/_astro/app.1234.css"]. */
  files: readonly string[];
  /** Changes whenever any file changes, so browsers pick up the new worker. */
  version: string;
  /** The site's Content-Security-Policy: saved files are served with it. */
  csp: string;
}

/** How long a page waits for the network before showing the saved copy. */
export const NETWORK_TIMEOUT_MS = 3000;

/** Where the previous version's build files are kept, for pages still open from it. */
export const PREVIOUS_CACHE = 'shkriuss-previous';

/**
 * Files in dist/ that are not served as-is, must not be cached, or aren't
 * needed offline (what crawlers and security researchers read).
 */
const NOT_PRECACHED = new Set(['_headers', '_redirects', 'sw.js', SECURITY_TXT, ROBOTS_TXT]);

/**
 * Folder in dist/ (and public/) for big files an app downloads only when the
 * person asks. They're never in the precache.
 */
export const ON_DEMAND_DIR = 'on-demand/';

/**
 * Turns built file paths into the URLs Cloudflare serves them at
 * ("privacy/index.html" → "/privacy/", "404.html" → "/404").
 */
export function precacheUrls(distFiles: readonly string[]): string[] {
  return distFiles
    .filter((file) => !NOT_PRECACHED.has(file) && !file.startsWith(ON_DEMAND_DIR))
    .map((file) => {
      if (file === 'index.html') return '/';
      if (file.endsWith('/index.html')) return `/${file.slice(0, -'index.html'.length)}`;
      if (file.endsWith('.html')) return `/${file.slice(0, -'.html'.length)}`;
      return `/${file}`;
    })
    .sort();
}

export function serviceWorkerSource({ files, version, csp }: ServiceWorkerOptions): string {
  return `// Generated by @shkriuss/astro-config at build time. Do not edit by hand.
// Source: packages/astro-config/src/service-worker.ts
const CACHE = 'shkriuss-${version}';
const PREVIOUS = '${PREVIOUS_CACHE}';
const NETWORK_TIMEOUT_MS = ${NETWORK_TIMEOUT_MS};
const CSP = ${JSON.stringify(csp)};
const PRECACHE = ${JSON.stringify([...files].sort(), null, 2)};

// A saved file, with the site's security policy now (audit 4 C-4).
function withPolicy(response) {
  if (!response || response.headers.get('Content-Security-Policy') === CSP) return response;
  const headers = new Headers(response.headers);
  headers.set('Content-Security-Policy', CSP);
  return new Response(response.body, {
    status: response.status,
    statusText: response.statusText,
    headers,
  });
}

self.addEventListener('install', (event) => {
  // Hashed build files never change: copy ones the previous version saved,
  // with this version's policy, so they needn't be changed each time they're served.
  const save = (cache, url) =>
    (url.startsWith('/_astro/') ? caches.match(url) : Promise.resolve(undefined)).then((saved) =>
      saved ? cache.put(url, withPolicy(saved)) : cache.add(url),
    );
  event.waitUntil(
    caches
      .open(CACHE)
      .then((cache) => Promise.all(PRECACHE.map((url) => save(cache, url))))
      .then(() => self.skipWaiting()),
  );
});

// The old versions' build files this one doesn't have, for pages still open
// from them. Only what's in their own caches, so it never grows.
async function keepPrevious(oldCaches) {
  await caches.delete(PREVIOUS);
  if (oldCaches.length === 0) return;
  const previous = await caches.open(PREVIOUS);
  const current = await caches.open(CACHE);
  for (const name of oldCaches) {
    const cache = await caches.open(name);
    for (const request of await cache.keys()) {
      if (!new URL(request.url).pathname.startsWith('/_astro/')) continue;
      if (await current.match(request)) continue;
      const response = await cache.match(request);
      if (response) await previous.put(request, withPolicy(response));
    }
  }
}

self.addEventListener('activate', (event) => {
  // Only this worker's old caches: an app's own (e.g. a downloaded model) stay.
  const old = (key) => key.startsWith('shkriuss-') && key !== CACHE && key !== PREVIOUS;
  event.waitUntil(
    caches
      .keys()
      .then((keys) => keys.filter(old))
      .then((oldCaches) =>
        keepPrevious(oldCaches)
          .catch(() => undefined)
          .then(() => Promise.all(oldCaches.map((key) => caches.delete(key)))),
      )
      .then(() => self.clients.claim()),
  );
});

self.addEventListener('fetch', (event) => {
  const request = event.request;
  if (request.method !== 'GET') return;
  const url = new URL(request.url);
  if (url.origin !== self.location.origin) return;
  // The server's answers (accounts, notifications) are never cached.
  if (url.pathname.startsWith('/api/')) return;

  if (url.pathname.startsWith('/_astro/')) {
    event.respondWith(
      caches.match(request).then((cached) => (cached ? withPolicy(cached) : fetch(request))),
    );
    return;
  }

  if (request.mode === 'navigate') {
    // The page's saved copy, whatever its query string. Online, Cloudflare
    // answers "/privacy" with a redirect to "/privacy/", which is how the
    // copy is saved: an address typed or bookmarked without its slash looks
    // for that too (audit 5 C-2). A file name (with a dot) is never a page.
    const page = url.origin + url.pathname;
    const slashed = /\\/[^/.]+$/.test(url.pathname) ? page + '/' : null;
    const saved = () =>
      caches
        .match(page, { ignoreSearch: true })
        .then((cached) => cached || (slashed && caches.match(slashed, { ignoreSearch: true })))
        .then(withPolicy);
    const network = fetch(request).then((response) =>
      // Not the page (a server error, or a 4xx a saved page can't have, like
      // the refusal of requests whose cookies are too big): the saved copy is
      // better, if there is one (audit 4 C-5). A redirect is passed on.
      response.ok || response.type === 'opaqueredirect'
        ? response
        : saved().then((cached) => cached || response),
    );
    // Network that doesn't answer in time: show the saved copy (or keep waiting if there's none).
    const slowNetwork = new Promise((resolve) => setTimeout(resolve, NETWORK_TIMEOUT_MS))
      .then(saved)
      .then((cached) => cached || network);
    event.respondWith(
      Promise.race([network, slowNetwork]).catch(() =>
        saved()
          .then((cached) => cached || caches.match('/404'))
          .then((cached) => cached || Response.error()),
      ),
    );
    return;
  }

  // Anything else saved (in any cache, including an app's on-demand files),
  // or the network.
  event.respondWith(
    caches.match(request).then((cached) => (cached ? withPolicy(cached) : fetch(request))),
  );
});

self.addEventListener('push', (event) => {
  let message = {};
  try {
    message = event.data ? event.data.json() : {};
  } catch {
    message = {};
  }
  const text = (value) => (typeof value === 'string' ? value : '');
  // Only a page on this site can be opened (never another website). The whole
  // address is kept: a path alone could start with "//" ("/.//x" becomes
  // "//x"), which would mean another website.
  let url = '/';
  try {
    const target = new URL(text(message.url) || '/', self.location.origin);
    if (target.origin === self.location.origin) url = target.href;
  } catch {
    url = '/';
  }
  const tag = text(message.tag);
  event.waitUntil(
    self.registration.showNotification(text(message.title) || 'Reminder', {
      body: text(message.body),
      tag: tag || undefined,
      // A repeat replaces the one before it with the same tag, and still
      // rings or buzzes (audit 3 F1-1). Chrome refuses renotify without a tag.
      renotify: Boolean(tag),
      icon: '/icon-192.png',
      data: { url },
    }),
  );
});

self.addEventListener('notificationclick', (event) => {
  event.notification.close();
  const url = (event.notification.data && event.notification.data.url) || '/';
  event.waitUntil(
    self.clients
      .matchAll({ type: 'window', includeUncontrolled: true })
      .then((windows) => (windows[0] ? windows[0].focus() : self.clients.openWindow(url))),
  );
});
`;
}
