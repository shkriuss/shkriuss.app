/**
 * Builds /sw.js: a small service worker that makes each site work offline.
 *
 * - On install it saves every built file (the "precache"). Hashed build
 *   files already saved by the previous version are copied, not downloaded
 *   again: they never change (Grammar's checker alone is 16 MB).
 * - Hashed build files (/_astro/…) are served from the cache first: they
 *   never change.
 * - Pages are fetched from the network first, so updates show up right away.
 *   If the network fails, or doesn't answer within NETWORK_TIMEOUT_MS (for
 *   example airplane mode with a VPN on, or a very weak signal), the saved
 *   copy is shown instead, and a late network answer still updates the cache.
 * - When a new version is deployed, the old cache is deleted. Caches an app
 *   manages itself (names not starting with "shkriuss-") are kept.
 * - Files under /on-demand/ are not saved: they're big, and an app downloads
 *   them only when the person asks (e.g. Grammar's Deep check model, about
 *   385 MB). The app saves them in its own cache, and they're served from
 *   there like any other saved file (docs/adr/0012).
 * - Push messages (notifications while the app is closed, docs/adr/0009)
 *   are shown as notifications. The browser has already decrypted them.
 * - Tapping a notification (e.g. a Calendar reminder) opens the app, or
 *   switches to it if it's already open.
 */

export interface ServiceWorkerOptions {
  /** URL paths to precache, e.g. ["/", "/privacy/", "/_astro/app.1234.css"]. */
  files: readonly string[];
  /** Changes whenever any file changes, so browsers pick up the new worker. */
  version: string;
}

/** How long a page waits for the network before showing the saved copy. */
export const NETWORK_TIMEOUT_MS = 3000;

/** Files in dist/ that are not served as-is, or must not be cached. */
const NOT_PRECACHED = new Set(['_headers', '_redirects', 'sw.js']);

/**
 * Folder in dist/ (and public/) for big files an app downloads only when the
 * person asks. They're never in the precache.
 */
export const ON_DEMAND_DIR = 'on-demand/';

/**
 * Turns built file paths into the URLs Cloudflare serves them at
 * ("privacy/index.html" → "/privacy/", "404.html" → "/404").
 */
export function precacheUrls(distFiles: readonly string[]): string[] {
  return distFiles
    .filter((file) => !NOT_PRECACHED.has(file) && !file.startsWith(ON_DEMAND_DIR))
    .map((file) => {
      if (file === 'index.html') return '/';
      if (file.endsWith('/index.html')) return `/${file.slice(0, -'index.html'.length)}`;
      if (file.endsWith('.html')) return `/${file.slice(0, -'.html'.length)}`;
      return `/${file}`;
    })
    .sort();
}

export function serviceWorkerSource({ files, version }: ServiceWorkerOptions): string {
  return `// Generated by @shkriuss/astro-config at build time. Do not edit by hand.
// Source: packages/astro-config/src/service-worker.ts
const CACHE = 'shkriuss-${version}';
const NETWORK_TIMEOUT_MS = ${NETWORK_TIMEOUT_MS};
const PRECACHE = ${JSON.stringify([...files].sort(), null, 2)};

self.addEventListener('install', (event) => {
  // Hashed build files never change: copy ones the previous version saved.
  const save = (cache, url) =>
    (url.startsWith('/_astro/') ? caches.match(url) : Promise.resolve(undefined)).then((saved) =>
      saved ? cache.put(url, saved) : cache.add(url),
    );
  event.waitUntil(
    caches
      .open(CACHE)
      .then((cache) => Promise.all(PRECACHE.map((url) => save(cache, url))))
      .then(() => self.skipWaiting()),
  );
});

self.addEventListener('activate', (event) => {
  // Only this worker's old caches: an app's own (e.g. a downloaded model) stay.
  const old = (key) => key.startsWith('shkriuss-') && key !== CACHE;
  event.waitUntil(
    caches
      .keys()
      .then((keys) => Promise.all(keys.filter(old).map((key) => caches.delete(key))))
      .then(() => self.clients.claim()),
  );
});

self.addEventListener('fetch', (event) => {
  const request = event.request;
  if (request.method !== 'GET') return;
  const url = new URL(request.url);
  if (url.origin !== self.location.origin) return;
  // The server's answers (accounts, notifications) are never cached.
  if (url.pathname.startsWith('/api/')) return;

  if (url.pathname.startsWith('/_astro/')) {
    event.respondWith(caches.match(request).then((cached) => cached || fetch(request)));
    return;
  }

  if (request.mode === 'navigate') {
    // One copy per page, whatever its query string.
    const page = url.origin + url.pathname;
    const saved = () => caches.match(page, { ignoreSearch: true });
    // Fetch the page and save a fresh copy for next time.
    const network = fetch(request).then((response) => {
      // A server error: the saved copy is better, if there is one.
      if (response.status >= 500) return saved().then((cached) => cached || response);
      // Only pages are saved, not other files opened directly (like a big download).
      const isPage = (response.headers.get('content-type') || '').startsWith('text/html');
      if (!response.ok || !isPage) return response;
      const copy = response.clone();
      return caches
        .open(CACHE)
        .then((cache) => cache.put(page, copy))
        .then(
          () => response,
          () => response,
        );
    });
    // Keep the worker alive until the network answers, even after a saved copy was shown.
    event.waitUntil(network.catch(() => undefined));
    // Network that doesn't answer in time: show the saved copy (or keep waiting if there's none).
    const slowNetwork = new Promise((resolve) => setTimeout(resolve, NETWORK_TIMEOUT_MS))
      .then(saved)
      .then((cached) => cached || network);
    event.respondWith(
      Promise.race([network, slowNetwork]).catch(() =>
        saved()
          .then((cached) => cached || caches.match('/404'))
          .then((cached) => cached || Response.error()),
      ),
    );
    return;
  }

  // Anything else saved (in any cache, including an app's on-demand files),
  // or the network.
  event.respondWith(
    caches.match(request).then((cached) => cached || fetch(request)),
  );
});

self.addEventListener('push', (event) => {
  let message = {};
  try {
    message = event.data ? event.data.json() : {};
  } catch {
    message = {};
  }
  const text = (value) => (typeof value === 'string' ? value : '');
  // Only a page on this site can be opened (never another website).
  let url = '/';
  try {
    const target = new URL(text(message.url) || '/', self.location.origin);
    if (target.origin === self.location.origin) url = target.pathname + target.search + target.hash;
  } catch {
    url = '/';
  }
  event.waitUntil(
    self.registration.showNotification(text(message.title) || 'Reminder', {
      body: text(message.body),
      tag: text(message.tag) || undefined,
      icon: '/icon-192.png',
      data: { url },
    }),
  );
});

self.addEventListener('notificationclick', (event) => {
  event.notification.close();
  const url = (event.notification.data && event.notification.data.url) || '/';
  event.waitUntil(
    self.clients
      .matchAll({ type: 'window', includeUncontrolled: true })
      .then((windows) => (windows[0] ? windows[0].focus() : self.clients.openWindow(url))),
  );
});
`;
}
